#!/usr/bin/env python3
"""T6-G: how much ground do two lineages of the same seed actually share?

The gate for the reconciliation chain (T4-CN node compatibility, T4-CM merge workbench,
T4-CS code-layer merge). Those tickets assume that two runs of one seed each solve parts the
other did not, so that reconciling them yields something neither has. That assumption had never
been measured, because until retention shipped there was only ever one lineage in the graph.

Four axes, per the ticket:

  1. criteria overlap    -- same criterion, decidable by key (a hash of the criterion text) and,
                            where available, by the code digest it was judged against
  2. goal overlap        -- same goal description, exact after normalising case and whitespace
  3. ecosystem facts     -- resolved symbol -> package facts
  4. contradictions      -- the same criterion with opposite verdicts in different lineages

Axis 2 is deliberately EXACT rather than semantic. A semantic comparator is a model call and this
script must stay offline; exact matching is a FLOOR on the overlap, so a thin exact overlap plus a
thin semantic one cannot be distinguished here, but a thin exact overlap that is entirely
template-generated is already decisive (see --explain).

Usage:
  scripts/lineage_overlap.py                       # population: every lineage in the graph
  scripts/lineage_overlap.py <lineageA> <lineageB>  # just this pair
  scripts/lineage_overlap.py --explain              # also list the most-shared descriptions
  scripts/lineage_overlap.py --json                 # machine-readable

Reads the graph over the Neo4j HTTP endpoint (no driver dependency) and the on-disk symbol cache.
Never writes anything. Exit 0 unless the graph is unreachable.
"""

import argparse
import base64
import json
import os
import sys
import urllib.error
import urllib.request
from collections import defaultdict

NEO4J_URL = os.environ.get("NEO4J_HTTP_URL", "http://localhost:7474/db/neo4j/tx/commit")
NEO4J_USER = os.environ.get("NEO4J_USER", "neo4j")
NEO4J_PASSWORD = os.environ.get("NEO4J_PASSWORD", "your_password")
SYMBOL_CACHE = os.environ.get(
    "SYMBOL_CACHE", os.path.join(os.environ.get("FILE_BASE_PATH", "data/firestarter"),
                                "cache", "symbol-imports.json"))

# A shared item present in this many lineages is regenerated by every run, so transferring it
# between two of them gains nothing. Expressed as a share of the lineages actually present rather
# than a fixed count, so it stays meaningful as the corpus grows.
UBIQUITY_SHARE = 0.5


def cypher(statement):
    """Rows for one read-only statement, as lists of values in column order."""
    payload = json.dumps({"statements": [{"statement": statement}]}).encode()
    auth = base64.b64encode(f"{NEO4J_USER}:{NEO4J_PASSWORD}".encode()).decode()
    request = urllib.request.Request(
        NEO4J_URL, data=payload,
        headers={"Content-Type": "application/json", "Authorization": "Basic " + auth})
    with urllib.request.urlopen(request, timeout=30) as response:
        body = json.load(response)
    if body.get("errors"):
        raise RuntimeError(body["errors"])
    return [row["row"] for row in body["results"][0]["data"]]


# ---------------------------------------------------------------------------
# measurement (pure — takes rows, returns numbers, so it is testable offline)
# ---------------------------------------------------------------------------

def group_by_item(rows):
    """{item: set(lineages)} from (item, lineage) rows, ignoring blank items."""
    grouped = defaultdict(set)
    for item, lineage in rows:
        if item is None or str(item).strip() == "" or lineage is None:
            continue
        grouped[str(item)].add(lineage)
    return grouped


def overlap_profile(grouped, lineage_count, restrict=None):
    """How much of the content is unique to one lineage, shared, or present in nearly all."""
    if restrict is not None:
        grouped = {item: (lineages & restrict) for item, lineages in grouped.items()}
        grouped = {item: lineages for item, lineages in grouped.items() if lineages}
        lineage_count = len(restrict)
    total = len(grouped)
    unique = sum(1 for lineages in grouped.values() if len(lineages) == 1)
    shared = total - unique
    ubiquity_threshold = max(2, int(lineage_count * UBIQUITY_SHARE))
    ubiquitous = sum(1 for lineages in grouped.values() if len(lineages) >= ubiquity_threshold)
    return {
        "distinct_items": total,
        "unique_to_one_lineage": unique,
        "shared_by_two_or_more": shared,
        "shared_share": (shared / total) if total else 0.0,
        "present_in_at_least": ubiquity_threshold,
        "ubiquitous": ubiquitous,
        # The number the gate turns on: shared ground that is NOT regenerated by every run anyway.
        "shared_and_not_ubiquitous": shared - ubiquitous,
    }


def overlap_by_origin(rows):
    """Shared share per goal role — the axis that separates dictated work from discovered work.

    A merge is only interesting for what a lineage FOUND OUT that another did not. The seed's own
    root goal and the deterministic injectors regenerate identically in every run, so their overlap
    is free and transferring it gains nothing. Splitting the same overlap measurement by the role
    that produced the goal separates the two, without judging any description's content.
    """
    descriptions = defaultdict(lambda: defaultdict(set))
    for description, role, lineage in rows:
        if description is None or lineage is None:
            continue
        descriptions[role or "unknown"][str(description)].add(lineage)
    profile = {}
    for role, items in descriptions.items():
        shared = sum(1 for lineages in items.values() if len(lineages) > 1)
        profile[role] = {
            "distinct_descriptions": len(items),
            "shared": shared,
            "shared_share": shared / len(items) if items else 0.0,
        }
    return dict(sorted(profile.items(), key=lambda kv: -kv[1]["distinct_descriptions"]))


def contradiction_profile(rows):
    """Shared criteria whose verdicts disagree between lineages — same key, both True and False."""
    verdicts = defaultdict(set)
    lineages = defaultdict(set)
    for key, lineage, passed in rows:
        if key is None or lineage is None or passed is None:
            continue
        verdicts[str(key)].add(bool(passed))
        lineages[str(key)].add(lineage)
    shared = [key for key, ls in lineages.items() if len(ls) > 1]
    contradictory = [key for key in shared if len(verdicts[key]) > 1]
    return {
        "shared_criteria": len(shared),
        "contradictory": len(contradictory),
        "contradictory_share": (len(contradictory) / len(shared)) if shared else 0.0,
    }


def ecosystem_facts(cache_path):
    """Resolved symbol -> package facts, and whether they are per-lineage at all."""
    try:
        with open(cache_path) as handle:
            cache = json.load(handle)
    except (OSError, ValueError):
        return {"available": False, "facts": 0, "scope": "unreadable", "path": cache_path}
    entries = cache.get("entries", cache) if isinstance(cache, dict) else {}
    return {
        "available": True,
        "facts": len(entries) if isinstance(entries, dict) else 0,
        # The finding, not a configuration detail: these facts live in ONE file that every run of
        # every lineage reads and writes, so they are already fully shared and there is nothing
        # for a graph merge to reconcile.
        "scope": "single shared on-disk cache — already common to all lineages",
        "path": cache_path,
    }


def verdict(criteria, goals, contradictions, by_origin, discovered_roles=("analysis",)):
    """The decision the ticket committed to in advance, applied to the measured numbers.

    The aggregate share is reported, but the call turns on the DISCOVERED share: a lineage's own
    findings, as opposed to the goals the seed and the deterministic injectors dictate. Judging the
    aggregate would count the seed's root goal and every template-generated repair item as shared
    ground worth reconciling, and those cost nothing to regenerate.
    """
    transferable = criteria["shared_and_not_ubiquitous"] + goals["shared_and_not_ubiquitous"]
    total = criteria["distinct_items"] + goals["distinct_items"]
    aggregate_share = (transferable / total) if total else 0.0

    discovered = [by_origin[role] for role in discovered_roles if role in by_origin]
    discovered_total = sum(p["distinct_descriptions"] for p in discovered)
    discovered_shared = sum(p["shared"] for p in discovered)
    discovered_share = (discovered_shared / discovered_total) if discovered_total else 0.0

    if discovered_share < 0.05:
        call = "THIN — merging two lineages of one seed buys little"
    elif discovered_share < 0.20:
        call = "MARGINAL — some transferable ground, dominated by regenerated content"
    else:
        call = "SUBSTANTIAL — the numbers become design input for reconciliation"
    return {
        "transferable_items": transferable,
        "total_items": total,
        "transferable_share": aggregate_share,
        "discovered_roles": list(discovered_roles),
        "discovered_total": discovered_total,
        "discovered_shared": discovered_shared,
        "discovered_share": discovered_share,
        "contradictory_share_of_shared_criteria": contradictions["contradictory_share"],
        "call": call,
    }


# ---------------------------------------------------------------------------
# reporting
# ---------------------------------------------------------------------------

def collect(restrict=None):
    lineage_rows = cypher(
        "MATCH (n) WHERE n.lineageId IS NOT NULL "
        "RETURN n.lineageId AS lineage, count(n) AS nodes ORDER BY nodes DESC")
    lineages = {lineage: nodes for lineage, nodes in lineage_rows}
    if restrict:
        missing = [l for l in restrict if l not in lineages]
        if missing:
            raise SystemExit(f"no such lineage in the graph: {', '.join(missing)}")

    criterion_rows = cypher(
        "MATCH (c:CriterionResult) RETURN c.criterionKey AS key, c.lineageId AS lineage")
    digest_rows = cypher(
        "MATCH (c:CriterionResult) WHERE c.codeDigest IS NOT NULL AND c.codeDigest <> '' "
        "RETURN c.criterionKey + '|' + c.codeDigest AS key, c.lineageId AS lineage")
    goal_rows = cypher(
        "MATCH (g:Goal) WHERE g.description IS NOT NULL "
        "RETURN toLower(trim(g.description)) AS description, g.lineageId AS lineage")
    origin_rows = cypher(
        "MATCH (g:Goal) WHERE g.description IS NOT NULL "
        "RETURN toLower(trim(g.description)) AS description, g.role AS role, g.lineageId AS lineage")
    verdict_rows = cypher(
        "MATCH (c:CriterionResult) WHERE c.criterionKey IS NOT NULL "
        "RETURN c.criterionKey AS key, c.lineageId AS lineage, c.passed AS passed")
    if restrict:
        keep = set(restrict)
        verdict_rows = [r for r in verdict_rows if r[1] in keep]

    scope = set(restrict) if restrict else None
    if restrict:
        keep = set(restrict)
        origin_rows = [r for r in origin_rows if r[2] in keep]
    criteria = overlap_profile(group_by_item(criterion_rows), len(lineages), scope)
    digests = overlap_profile(group_by_item(digest_rows), len(lineages), scope)
    goals = overlap_profile(group_by_item(goal_rows), len(lineages), scope)
    contradictions = contradiction_profile(verdict_rows)
    by_origin = overlap_by_origin(origin_rows)
    return {
        "lineages": lineages,
        "scope": sorted(scope) if scope else "all",
        "criteria_by_key": criteria,
        "criteria_by_key_and_digest": digests,
        "criterion_digest_coverage": {
            "results_total": len(criterion_rows),
            "results_with_digest": len(digest_rows),
        },
        "goals_by_description": goals,
        "goals_by_origin": by_origin,
        "contradictions": contradictions,
        "ecosystem_facts": ecosystem_facts(SYMBOL_CACHE),
        "verdict": verdict(criteria, goals, contradictions, by_origin),
    }


def most_shared_descriptions(limit=20):
    return cypher(
        "MATCH (g:Goal) WHERE g.description IS NOT NULL "
        "WITH toLower(trim(g.description)) AS d, collect(DISTINCT g.lineageId) AS ls "
        "WHERE size(ls) > 1 "
        "RETURN size(ls) AS n, substring(d, 0, 100) AS description "
        f"ORDER BY n DESC LIMIT {int(limit)}")


def render(report, explain=False):
    out = []
    out.append(f"LINEAGE OVERLAP (T6-G) — {len(report['lineages'])} lineages in the graph")
    scope = report["scope"]
    out.append(f"  scope: {scope if scope == 'all' else ', '.join(scope)}")
    out.append("")

    def axis(title, profile):
        out.append(f"  {title}")
        out.append(f"    distinct items                : {profile['distinct_items']}")
        out.append(f"    unique to one lineage         : {profile['unique_to_one_lineage']}"
                   f" ({1 - profile['shared_share']:.1%})")
        out.append(f"    shared by two or more         : {profile['shared_by_two_or_more']}"
                   f" ({profile['shared_share']:.1%})")
        out.append(f"    of those, in >= {profile['present_in_at_least']} lineages   :"
                   f" {profile['ubiquitous']}  (regenerated by every run — nothing to transfer)")
        out.append(f"    TRANSFERABLE (shared, not ubiquitous): {profile['shared_and_not_ubiquitous']}")
        out.append("")

    axis("axis 1 — criteria, by criterion key", report["criteria_by_key"])
    coverage = report["criterion_digest_coverage"]
    out.append(f"  axis 1b — criteria, by key AND code digest")
    out.append(f"    digest present on             : {coverage['results_with_digest']}"
               f" of {coverage['results_total']} results"
               f" ({coverage['results_with_digest'] / max(1, coverage['results_total']):.1%})")
    out.append("    NOTE: the ticket calls this the only axis decidable without heuristics, and it")
    out.append("          is almost entirely unpopulated in the accumulated data.")
    out.append("")
    axis("axis 2 — goals, by exact description", report["goals_by_description"])

    out.append("  axis 2b — the same overlap, split by what PRODUCED the goal")
    out.append("    (the seed's root goal and the deterministic injectors regenerate identically in")
    out.append("     every run, so their overlap is free; only discovered work is worth transferring)")
    for role, profile in report["goals_by_origin"].items():
        out.append(f"    {role:<22}: {profile['shared']:>4} shared of"
                   f" {profile['distinct_descriptions']:>4} distinct"
                   f"  ({profile['shared_share']:.1%})")
    out.append("")

    facts = report["ecosystem_facts"]
    out.append("  axis 3 — resolved ecosystem facts")
    out.append(f"    facts                         : {facts['facts']}")
    out.append(f"    scope                         : {facts['scope']}")
    out.append("")

    contradictions = report["contradictions"]
    out.append("  axis 4 — contradictions")
    out.append(f"    criteria shared across lineages: {contradictions['shared_criteria']}")
    out.append(f"    with opposite verdicts        : {contradictions['contradictory']}"
               f" ({contradictions['contradictory_share']:.1%})")
    out.append("")

    call = report["verdict"]
    out.append(f"  VERDICT: {call['call']}")
    out.append(f"    discovered work shared: {call['discovered_shared']} of"
               f" {call['discovered_total']} ({call['discovered_share']:.1%})"
               f" — roles {', '.join(call['discovered_roles'])}")
    out.append(f"    aggregate transferable: {call['transferable_items']} of {call['total_items']}"
               f" ({call['transferable_share']:.1%})")
    out.append(f"    shared criteria that DISAGREE:"
               f" {call['contradictory_share_of_shared_criteria']:.1%}")

    if explain:
        out.append("")
        out.append("  WHAT IS ACTUALLY SHARED (most lineages first):")
        for count, description in most_shared_descriptions():
            out.append(f"    {count:>3}x  {description}")
    return "\n".join(out)


def main(argv=None):
    parser = argparse.ArgumentParser(description="T6-G cross-lineage overlap")
    parser.add_argument("lineages", nargs="*", help="restrict to these lineage ids (0 or 2+)")
    parser.add_argument("--explain", action="store_true",
                        help="list the most-shared goal descriptions")
    parser.add_argument("--json", action="store_true", help="machine-readable output")
    args = parser.parse_args(argv)

    if len(args.lineages) == 1:
        parser.error("give no lineages (population mode) or two or more")
    try:
        report = collect(args.lineages or None)
    except (urllib.error.URLError, OSError) as exc:
        print(f"graph unreachable at {NEO4J_URL}: {exc}", file=sys.stderr)
        return 1
    print(json.dumps(report, indent=2) if args.json else render(report, args.explain))
    return 0


if __name__ == "__main__":
    sys.exit(main())
