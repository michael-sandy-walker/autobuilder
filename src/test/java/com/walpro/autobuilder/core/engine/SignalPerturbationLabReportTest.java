package com.walpro.autobuilder.core.engine;

import com.walpro.autobuilder.core.engine.LabStateLibrary.LabState;
import com.walpro.autobuilder.core.engine.SignalPerturbationLab.Observation;
import com.walpro.autobuilder.core.engine.SignalPerturbationLab.Perturbation;
import com.walpro.autobuilder.core.lifecycle.BasicSignals;
import com.walpro.autobuilder.core.lifecycle.SignalType;
import org.junit.jupiter.api.Test;

import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * T4-J Phase 3b: the sweep driver.
 *
 * {@link #generateBoundaryReport()} runs the full (state x perturbation) grid — ablation of every
 * present signal (Q1), plus strength/age grids on the calibration shortlist (Q7) — and writes the
 * boundary map to {@code target/perturbation-lab-report.md}. The remaining tests pin known
 * decision behavior as regressions so the lab itself stays trustworthy.
 */
class SignalPerturbationLabReportTest {

    private static final List<SignalType> SHORTLIST = List.of(
            BasicSignals.MISSING_SYMBOL, BasicSignals.PLANNING_THROTTLED, BasicSignals.ROLE_MERGE);

    private static final double[] STRENGTH_GRID = {0.05, 0.25, 0.5, 1.0, 2.0, 3.0};
    private static final int[] AGE_GRID = {0, 1, 3, 5, 10, 20};

    // ---------------------------------------------------------------- the sweep

    @Test
    void generateBoundaryReport() throws Exception {
        StringBuilder md = new StringBuilder();
        md.append("# T4-J Phase 3 — frozen-state perturbation boundary map\n\n");
        md.append("Generated by SignalPerturbationLabReportTest#generateBoundaryReport. ");
        md.append("Decision deltas = mode / topRanked / order / firstEligible / eligibility flips; ");
        md.append("ticks[...] deltas are decay dynamics only.\n");

        Map<String, Integer> ablationFlips = new TreeMap<>();
        Map<String, Integer> ablationInert = new TreeMap<>();
        int fidelityAgree = 0, fidelityTotal = 0;

        for (LabState state : LabStateLibrary.all()) {
            Observation base = SignalPerturbationLab.observe(state.ctx(), state.world());
            md.append("\n## ").append(state.name()).append("\n\n");
            List<String> jitterTies = SignalPerturbationLab.subJitterPairs(base);
            md.append("baseline: mode=").append(base.mode())
              .append(base.haltedBeforeRanking() ? " HALTED" : "")
              .append(" | ranked=").append(base.rankedRoles())
              .append(" | firstEligible=").append(base.firstEligibleRole())
              .append(base.proposedSignals().isEmpty() ? "" : " | proposed=" + base.proposedSignals())
              .append(jitterTies.isEmpty() ? "" : " | jitterTies=" + jitterTies)
              .append("\n");

            if (state.recordedRanking() != null) {
                fidelityTotal++;
                // Compatible = the recorded production order agrees on every pair the lab says
                // is decided by more than the exploration jitter; order inside a jitter-tie was
                // a production coin-flip and carries no information.
                boolean agree = recordedOrderCompatible(state.recordedRanking(), base);
                if (agree) fidelityAgree++;
                md.append("fidelity: recorded=").append(state.recordedRanking())
                  .append(agree ? " COMPATIBLE" : " MISMATCH (age/context reconstruction limit)").append("\n");
            }

            List<Perturbation> grid = new ArrayList<>();
            List<SignalType> present = state.ctx().signals().keySet().stream().toList();
            for (SignalType type : present) grid.add(Perturbation.ablate(type));
            for (SignalType type : SHORTLIST) {
                if (!state.ctx().hasSignal(type)) continue;
                for (double v : STRENGTH_GRID) grid.add(Perturbation.strength(type, v));
                for (int v : AGE_GRID) grid.add(Perturbation.age(type, v));
            }
            if (state.ctx().hasSignal(BasicSignals.EVOLUTION_OCCURRED)) {
                for (int v : AGE_GRID) grid.add(Perturbation.age(BasicSignals.EVOLUTION_OCCURRED, v));
            }

            int inert = 0;
            for (Perturbation p : grid) {
                Observation obs = SignalPerturbationLab.observe(p.apply().apply(state.ctx()), state.world());
                List<String> deltas = obs.decisionDeltasVs(base);
                boolean isAblation = p.name().startsWith("ablate ");
                if (deltas.isEmpty()) {
                    inert++;
                    if (isAblation) ablationInert.merge(p.touches().name(), 1, Integer::sum);
                } else {
                    if (isAblation) ablationFlips.merge(p.touches().name(), 1, Integer::sum);
                    md.append("- **").append(p.name()).append("** -> ").append(String.join("; ", deltas)).append("\n");
                }
            }
            md.append("- (").append(inert).append("/").append(grid.size())
              .append(" perturbations decision-inert in this state)\n");
        }

        md.append("\n## Ablation summary (Q1): states where removing the signal flipped a decision\n\n");
        md.append("| signal | flips | inert |\n|---|--:|--:|\n");
        Map<String, Integer> allTypes = new TreeMap<>(ablationFlips);
        ablationInert.forEach((k, v) -> allTypes.putIfAbsent(k, 0));
        for (String type : allTypes.keySet()) {
            md.append("| ").append(type).append(" | ").append(ablationFlips.getOrDefault(type, 0))
              .append(" | ").append(ablationInert.getOrDefault(type, 0)).append(" |\n");
        }
        md.append("\nlog-derived ranking fidelity: ").append(fidelityAgree).append("/").append(fidelityTotal)
          .append(" recorded rankings compatible (age=1 reconstruction; jitter-ties uninformative).\n");

        Path out = Path.of("target", "perturbation-lab-report.md");
        Files.createDirectories(out.getParent());
        Files.writeString(out, md.toString());
        System.out.println("[lab] report written to " + out.toAbsolutePath());
        System.out.println("[lab] fidelity " + fidelityAgree + "/" + fidelityTotal);

        assertThat(out).exists();
    }

    // ---------------------------------------------------------------- pinned decisions

    @Test
    void bootstrapState_proposesBootstrapMode() {
        LabState s = named("canon: bootstrap");
        Observation base = SignalPerturbationLab.observe(s.ctx(), s.world());
        assertThat(base.mode()).isEqualTo("BOOTSTRAP");
        assertThat(base.rankedRoles()).doesNotContain("merge"); // BOOTSTRAP gate excludes merge
    }

    @Test
    void plateauFirstDetection_boostsMerge_sustainedPlateau_escalatesToReplan() {
        Observation first = observeNamed("canon: plateau-first");
        assertThat(first.mode()).isEqualTo("UNDIRECTED");
        assertThat(first.proposedSignals()).anyMatch(p -> p.startsWith("ROLE_MERGE="));

        Observation sustained = observeNamed("canon: plateau-sustained");
        assertThat(sustained.mode()).isEqualTo("REPLAN");
    }

    @Test
    void haltedState_endsCycleBeforeRanking() {
        Observation halted = observeNamed("canon: halted");
        assertThat(halted.haltedBeforeRanking()).isTrue();
        assertThat(halted.rankedRoles()).isEmpty();
    }

    @Test
    void ablatingEvolutionOccurred_dropsEvaluationFitness() {
        // Pending-evaluation proposes EVALUATE, whose gate ranks only the evaluation role —
        // so the corpus's "most load-bearing signal" effect shows as an evaluation-fitness drop
        // of W_SIGNAL*strength + recency here (merge is not ranked in this mode at all).
        LabState s = named("canon: pending-evaluation");
        Observation base = SignalPerturbationLab.observe(s.ctx(), s.world());
        Observation ablated = SignalPerturbationLab.observe(
                Perturbation.ablate(BasicSignals.EVOLUTION_OCCURRED).apply().apply(s.ctx()), s.world());
        assertThat(base.rankedRoles()).containsExactly("evaluation");
        assertThat(ablated.fitness().get("evaluation")).isLessThan(base.fitness().get("evaluation"));
    }

    @Test
    void plannerThrottle_blocksPlanner_untilStrongReplanOverride() {
        Observation throttled = observeNamed("canon: planner-throttled");
        assertThat(throttled.blockersByRole().get("planner"))
                .anyMatch(b -> b.contains("planning throttled"));

        Observation overridden = observeNamed("canon: planner-throttle-overridden");
        assertThat(overridden.blockersByRole().get("planner"))
                .noneMatch(b -> b.contains("planning throttled"));
    }

    @Test
    void buildBroken_boostsAnalysisAboveDepressedPlannerAndEvaluation() {
        Observation obs = observeNamed("canon: build-broken");
        assertThat(obs.topRankedRole()).isEqualTo("analysis");
        assertThat(obs.blockersByRole().get("planner")).contains("build_blocked");
    }

    @Test
    void logDerivedStates_loadAndProduceARanking() {
        List<LabState> states = LabStateLibrary.logDerivedStates();
        assertThat(states).isNotEmpty();
        for (LabState s : states) {
            Observation obs = SignalPerturbationLab.observe(s.ctx(), s.world());
            // mode may legitimately gate roles out (e.g. a REPLAN-shaped signal map ranks 3);
            // the state must still produce a non-empty ranking.
            assertThat(obs.rankedRoles()).as(s.name()).isNotEmpty();
        }
    }

    private static boolean recordedOrderCompatible(List<String> recorded, Observation base) {
        if (!recorded.containsAll(base.rankedRoles()) || recorded.size() != base.rankedRoles().size()) {
            return false; // different role set ranked => mode mismatch, not comparable
        }
        for (String a : base.fitness().keySet()) {
            for (String b : base.fitness().keySet()) {
                double gap = base.fitness().get(a) - base.fitness().get(b);
                if (gap > SignalPerturbationLab.JITTER
                        && recorded.indexOf(a) > recorded.indexOf(b)) {
                    return false;
                }
            }
        }
        return true;
    }

    private static LabState named(String name) {
        return LabStateLibrary.all().stream()
                .filter(s -> s.name().equals(name)).findFirst().orElseThrow();
    }

    private static Observation observeNamed(String name) {
        LabState s = named(name);
        return SignalPerturbationLab.observe(s.ctx(), s.world());
    }
}
