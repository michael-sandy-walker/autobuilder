#!/usr/bin/env python3
"""Tests for T6-G's overlap measurement. Stdlib only; no graph, no network.

The measurement functions take rows and return numbers, so the arithmetic behind a gate verdict is
checkable without a database. What is pinned here is the reasoning the verdict depends on: that
content every lineage regenerates is not counted as transferable ground, and that the call turns on
DISCOVERED work rather than on the aggregate.
"""

import unittest

import lineage_overlap as lo


class GroupByItem(unittest.TestCase):
    def test_collects_the_lineages_each_item_appears_in(self):
        grouped = lo.group_by_item([("a", "L1"), ("a", "L2"), ("b", "L1")])
        self.assertEqual({"a": {"L1", "L2"}, "b": {"L1"}}, grouped)

    def test_blank_and_missing_values_are_not_items(self):
        # A criterion with no key and a node with no lineage stamp are absences, not overlap of
        # nothing with nothing.
        grouped = lo.group_by_item([("", "L1"), (None, "L1"), ("a", None), ("  ", "L2")])
        self.assertEqual({}, grouped)


class OverlapProfile(unittest.TestCase):
    def test_separates_unique_from_shared(self):
        profile = lo.overlap_profile({"a": {"L1", "L2"}, "b": {"L1"}, "c": {"L2"}}, 2)
        self.assertEqual(3, profile["distinct_items"])
        self.assertEqual(2, profile["unique_to_one_lineage"])
        self.assertEqual(1, profile["shared_by_two_or_more"])

    def test_content_every_lineage_has_is_not_transferable(self):
        # The heart of the measurement: an item present in every lineage is regenerated by every
        # run, so moving it from one to another gains nothing and it must not inflate the share.
        # Eight lineages, so the relative threshold lands at four and can actually discriminate.
        # Below about four lineages a 50% threshold equals "shared at all" and the two categories
        # collapse — the measurement needs an accumulated corpus to say anything, which is why it
        # could not be run before retention shipped.
        everywhere = {f"L{i}" for i in range(1, 9)}
        grouped = {f"seed{i}": set(everywhere) for i in range(4)}
        grouped["found-only-here"] = {"L1"}
        grouped["found-twice"] = {"L1", "L2"}
        profile = lo.overlap_profile(grouped, len(everywhere))
        self.assertEqual(4, profile["present_in_at_least"])
        self.assertEqual(5, profile["shared_by_two_or_more"])
        self.assertEqual(4, profile["ubiquitous"])
        self.assertEqual(1, profile["shared_and_not_ubiquitous"])

    def test_the_ubiquity_threshold_scales_with_the_corpus(self):
        # Relative to the lineages present, never a fixed count — the same item must not become
        # "regenerated" or stop being so merely because more runs accumulated.
        few = lo.overlap_profile({"a": {"L1", "L2"}}, 4)
        many = lo.overlap_profile({"a": {"L1", "L2"}}, 40)
        self.assertEqual(2, few["present_in_at_least"])
        self.assertEqual(20, many["present_in_at_least"])
        self.assertEqual(1, few["ubiquitous"])
        self.assertEqual(0, many["ubiquitous"])

    def test_restricting_to_a_pair_ignores_other_lineages(self):
        grouped = {"a": {"L1", "L3"}, "b": {"L1", "L2"}, "c": {"L3"}}
        profile = lo.overlap_profile(grouped, 3, restrict={"L1", "L2"})
        # "a" survives as L1-only, "c" drops out entirely, "b" is the only shared item.
        self.assertEqual(2, profile["distinct_items"])
        self.assertEqual(1, profile["shared_by_two_or_more"])


class OverlapByOrigin(unittest.TestCase):
    def test_reports_the_shared_share_per_producing_role(self):
        rows = [
            ("the seed", "system", "L1"), ("the seed", "system", "L2"),
            ("found A", "analysis", "L1"),
            ("found B", "analysis", "L2"),
            ("planned X", "planner", "L1"), ("planned X", "planner", "L2"),
        ]
        profile = lo.overlap_by_origin(rows)
        self.assertEqual(1.0, profile["system"]["shared_share"])
        self.assertEqual(1.0, profile["planner"]["shared_share"])
        # Two lineages each found something different: no discovered overlap at all.
        self.assertEqual(0.0, profile["analysis"]["shared_share"])

    def test_a_missing_role_is_reported_rather_than_dropped(self):
        profile = lo.overlap_by_origin([("x", None, "L1")])
        self.assertEqual(1, profile["unknown"]["distinct_descriptions"])


class Contradictions(unittest.TestCase):
    def test_only_criteria_present_in_more_than_one_lineage_can_contradict(self):
        rows = [("k1", "L1", True), ("k1", "L1", False)]  # disagreement inside one lineage
        self.assertEqual(0, lo.contradiction_profile(rows)["shared_criteria"])

    def test_opposite_verdicts_across_lineages_are_contradictions(self):
        rows = [("k1", "L1", True), ("k1", "L2", False),
                ("k2", "L1", True), ("k2", "L2", True)]
        profile = lo.contradiction_profile(rows)
        self.assertEqual(2, profile["shared_criteria"])
        self.assertEqual(1, profile["contradictory"])
        self.assertEqual(0.5, profile["contradictory_share"])

    def test_a_missing_verdict_is_not_a_disagreement(self):
        rows = [("k1", "L1", True), ("k1", "L2", None)]
        self.assertEqual(0, lo.contradiction_profile(rows)["contradictory"])


class Verdict(unittest.TestCase):
    EMPTY_CONTRADICTIONS = {"contradictory_share": 0.0}

    @staticmethod
    def _profile(total, shared, ubiquitous=0):
        return {"distinct_items": total, "shared_by_two_or_more": shared,
                "shared_and_not_ubiquitous": shared - ubiquitous}

    def test_ubiquitous_shared_content_does_not_make_the_ground_substantial(self):
        # The case measured in the field: heavy aggregate overlap, all of it the seed's own plan,
        # and essentially no discovered overlap. The honest call is THIN.
        by_origin = {"analysis": {"distinct_descriptions": 288, "shared": 3, "shared_share": 0.01}}
        call = lo.verdict(self._profile(986, 87, 11), self._profile(700, 46, 11),
                          self.EMPTY_CONTRADICTIONS, by_origin)
        self.assertIn("THIN", call["call"])
        self.assertAlmostEqual(3 / 288, call["discovered_share"])

    def test_substantial_discovered_overlap_is_reported_as_such(self):
        by_origin = {"analysis": {"distinct_descriptions": 100, "shared": 40, "shared_share": 0.4}}
        call = lo.verdict(self._profile(100, 40), self._profile(100, 40),
                          self.EMPTY_CONTRADICTIONS, by_origin)
        self.assertIn("SUBSTANTIAL", call["call"])

    def test_the_aggregate_share_is_still_reported_even_when_it_disagrees(self):
        # Both numbers are published; the call names which one it used, so a reader can see that a
        # 6.6% aggregate and a 1.0% discovered share are different claims.
        by_origin = {"analysis": {"distinct_descriptions": 288, "shared": 3, "shared_share": 0.01}}
        call = lo.verdict(self._profile(986, 87, 11), self._profile(700, 46, 11),
                          self.EMPTY_CONTRADICTIONS, by_origin)
        self.assertGreater(call["transferable_share"], call["discovered_share"])
        self.assertEqual(["analysis"], call["discovered_roles"])

    def test_no_content_at_all_does_not_divide_by_zero(self):
        call = lo.verdict(self._profile(0, 0), self._profile(0, 0), self.EMPTY_CONTRADICTIONS, {})
        self.assertEqual(0.0, call["discovered_share"])
        self.assertIn("THIN", call["call"])


class EcosystemFacts(unittest.TestCase):
    def test_an_unreadable_cache_is_reported_not_raised(self):
        facts = lo.ecosystem_facts("/nonexistent/symbol-imports.json")
        self.assertFalse(facts["available"])
        self.assertEqual(0, facts["facts"])


if __name__ == "__main__":
    unittest.main()
