/**
 * T4-J Phase 3b: the sweep driver.
 *
 * {@link #generateBoundaryReport()} runs the full (state x perturbation) grid — ablation of every
 * present signal (Q1), plus strength/age grids on the calibration shortlist (Q7) — and writes the
 * boundary map to {@code target/signal-perturbation-report.md}. The remaining tests pin known
 * decision behavior as regressions so the observer itself stays trustworthy.
 */
class SignalPerturbationSweepTest {

    private static final List<SignalType> SHORTLIST = List.of(
            BasicSignals.MISSING_SYMBOL, BasicSignals.PLANNING_THROTTLED, BasicSignals.ROLE_MERGE);

    private static final double[] STRENGTH_GRID = {0.05, 0.25, 0.5, 1.0, 2.0, 3.0};
    private static final int[] AGE_GRID = {0, 1, 3, 5, 10, 20};
    // Decay never flips a same-cycle selection decision (ranking reads strength+age only), but
    // the interpretation prompt renders decayPerCycle — the grid measures that reach.
    private static final double[] DECAY_GRID = {0.0, 0.05, 0.10, 0.25, 0.5, 1.0};

    // ---------------------------------------------------------------- the sweep

    @Test
    void generateBoundaryReport() throws Exception {
        StringBuilder md = new StringBuilder();
        md.append("# T4-J Phase 3 — frozen-state perturbation boundary map\n\n");
        md.append("Generated by SignalPerturbationSweepTest#generateBoundaryReport. ");
        md.append("Decision deltas = mode / topRanked / order / firstEligible / eligibility flips; ");
        md.append("ticks[...] deltas are decay dynamics only.\n");

        Map<String, Integer> ablationFlips = new TreeMap<>();
        Map<String, Integer> ablationInert = new TreeMap<>();
        // Phase 3c: perturbed signal type -> prompt name -> perturbations changing that prompt
        Map<String, Map<String, Integer>> promptReach = new TreeMap<>();
        Map<String, Integer> promptReachTotals = new TreeMap<>();
        List<String> renderFailures = new ArrayList<>();
        int fidelityAgree = 0, fidelityTotal = 0;

        for (FrozenState state : FrozenStateFixtures.all()) {
            Observation base = FrozenCycleObserver.observe(state.ctx(), state.world());
            md.append("\n## ").append(state.name()).append("\n\n");
            List<String> jitterTies = FrozenCycleObserver.subJitterPairs(base);
            md.append("baseline: mode=").append(base.mode())
              .append(base.haltedBeforeRanking() ? " HALTED" : "")
              .append(" | ranked=").append(base.rankedRoles())
              .append(" | firstEligible=").append(base.firstEligibleRole())
              .append(base.proposedSignals().isEmpty() ? "" : " | proposed=" + base.proposedSignals())
              .append(jitterTies.isEmpty() ? "" : " | jitterTies=" + jitterTies)
              .append("\n");

            if (state.recordedRanking() != null) {
                fidelityTotal++;
                // Compatible = the recorded production order agrees on every pair the observer says
                // is decided by more than the exploration jitter; order inside a jitter-tie was
                // a production coin-flip and carries no information.
                boolean agree = recordedOrderCompatible(state.recordedRanking(), base);
                if (agree) fidelityAgree++;
                md.append("fidelity: recorded=").append(state.recordedRanking())
                  .append(agree ? " COMPATIBLE" : " MISMATCH (age/context reconstruction limit)").append("\n");
                List<String> candidates = coinFlipCandidates(base);
                String selectedComparison = Objects.equals(state.recordedFirstSelected(), base.firstEligibleRole())
                        ? " MATCH"
                        : candidates.contains(state.recordedFirstSelected())
                                ? " TIE-COMPATIBLE (candidates=" + candidates + ")"
                                : " MISMATCH";
                md.append("fidelity: recordedMode=").append(state.recordedMode())
                  .append(Objects.equals(state.recordedMode(), base.mode()) ? " MATCH" : " MISMATCH")
                  .append(" | recordedFirstSelected=").append(state.recordedFirstSelected())
                  .append(selectedComparison).append("\n");
            }

            List<Perturbation> grid = new ArrayList<>();
            List<SignalType> present = state.ctx().signals().keySet().stream().toList();
            for (SignalType type : present) grid.add(Perturbation.ablate(type));
            for (SignalType type : SHORTLIST) {
                if (!state.ctx().hasSignal(type)) continue;
                for (double v : STRENGTH_GRID) grid.add(Perturbation.strength(type, v));
                for (int v : AGE_GRID) grid.add(Perturbation.age(type, v));
                for (double v : DECAY_GRID) grid.add(Perturbation.decay(type, v));
            }
            if (state.ctx().hasSignal(BasicSignals.EVOLUTION_OCCURRED)) {
                for (int v : AGE_GRID) grid.add(Perturbation.age(BasicSignals.EVOLUTION_OCCURRED, v));
            }

            Map<String, String> basePrompts = safeRenderAll(state.ctx(), state.name(), renderFailures);

            int inert = 0;
            for (Perturbation p : grid) {
                CycleContextData perturbedCtx = p.apply().apply(state.ctx());
                Observation obs = FrozenCycleObserver.observe(perturbedCtx, state.world());
                List<String> deltas = obs.decisionDeltasVs(base);
                boolean isAblation = p.name().startsWith("ablate ");
                if (deltas.isEmpty()) {
                    inert++;
                    if (isAblation) ablationInert.merge(p.touches().name(), 1, Integer::sum);
                } else {
                    if (isAblation) ablationFlips.merge(p.touches().name(), 1, Integer::sum);
                    md.append("- **").append(p.name()).append("** -> ").append(String.join("; ", deltas)).append("\n");
                }

                // Phase 3c: does the perturbation reach any LLM prompt text?
                if (basePrompts != null && !perturbedCtx.signals().equals(state.ctx().signals())) {
                    Map<String, String> perturbedPrompts =
                            safeRenderAll(perturbedCtx, state.name() + " " + p.name(), renderFailures);
                    if (perturbedPrompts != null) {
                        promptReachTotals.merge(p.touches().name(), 1, Integer::sum);
                        AgentPromptRenderer.diff(basePrompts, perturbedPrompts).keySet().forEach(prompt ->
                                promptReach.computeIfAbsent(p.touches().name(), k -> new TreeMap<>())
                                        .merge(prompt, 1, Integer::sum));
                    }
                }
            }
            md.append("- (").append(inert).append("/").append(grid.size())
              .append(" perturbations decision-inert in this state)\n");
        }

        md.append("\n## Ablation summary (Q1): states where removing the signal flipped a decision\n\n");
        md.append("| signal | flips | inert |\n|---|--:|--:|\n");
        Map<String, Integer> allTypes = new TreeMap<>(ablationFlips);
        ablationInert.forEach((k, v) -> allTypes.putIfAbsent(k, 0));
        for (String type : allTypes.keySet()) {
            md.append("| ").append(type).append(" | ").append(ablationFlips.getOrDefault(type, 0))
              .append(" | ").append(ablationInert.getOrDefault(type, 0)).append(" |\n");
        }
        md.append("\nlog-derived ranking fidelity: ").append(fidelityAgree).append("/").append(fidelityTotal)
          .append(" recorded rankings compatible (age=1 reconstruction; jitter-ties uninformative).\n");

        md.append("\n## Prompt reach (Phase 3c): perturbations changing each rendered prompt\n\n");
        md.append("Renders the five prompts per the production adapters' argument derivations; ");
        md.append("a cell is `changed/perturbations`. The analysis prompt lists every present signal ");
        md.append("as NAME=strength and the interpretation prompt embeds the whole signal map, so any ");
        md.append("signal change is expected to reach those two; reach beyond them marks a dedicated ");
        md.append("prompt path and routes the signal to Phase 4.\n\n");
        md.append("| signal | perturbations | planner | evolution | evaluation | analysis | interpretation |\n");
        md.append("|---|--:|--:|--:|--:|--:|--:|\n");
        for (String type : promptReachTotals.keySet()) {
            Map<String, Integer> reach = promptReach.getOrDefault(type, Map.of());
            md.append("| ").append(type).append(" | ").append(promptReachTotals.get(type));
            for (String prompt : AgentPromptRenderer.PROMPTS) {
                md.append(" | ").append(reach.getOrDefault(prompt, 0));
            }
            md.append(" |\n");
        }
        if (!renderFailures.isEmpty()) {
            md.append("\nrender failures (state/perturbation -> error):\n");
            renderFailures.forEach(f -> md.append("- ").append(f).append("\n"));
        }

        Path out = Path.of("target", "signal-perturbation-report.md");
        Files.createDirectories(out.getParent());
        Files.writeString(out, md.toString());
        System.out.println("[sweep] report written to " + out.toAbsolutePath());
        System.out.println("[sweep] fidelity " + fidelityAgree + "/" + fidelityTotal);

        assertThat(out).exists();
    }

    private static Map<String, String> safeRenderAll(CycleContextData ctx, String label, List<String> failures) {
        try {
            return AgentPromptRenderer.renderAll(ctx);
        } catch (Exception e) {
            failures.add(label + " -> " + e.getClass().getSimpleName() + ": " + e.getMessage());
            return null;
        }
    }

    // ---------------------------------------------------------------- pinned decisions

    @Test
    void bootstrapState_proposesBootstrapMode() {
        FrozenState s = named("canon: bootstrap");
        Observation base = FrozenCycleObserver.observe(s.ctx(), s.world());
        assertThat(base.mode()).isEqualTo("BOOTSTRAP");
        assertThat(base.rankedRoles()).doesNotContain("merge"); // BOOTSTRAP gate excludes merge
    }

    @Test
    void plateauFirstDetection_boostsMerge_sustainedPlateau_escalatesToReplan() {
        Observation first = observeNamed("canon: plateau-first");
        assertThat(first.mode()).isEqualTo("UNDIRECTED");
        assertThat(first.proposedSignals()).anyMatch(p -> p.startsWith("ROLE_MERGE="));

        Observation sustained = observeNamed("canon: plateau-sustained");
        assertThat(sustained.mode()).isEqualTo("REPLAN");
    }

    @Test
    void haltedState_endsCycleBeforeRanking() {
        Observation halted = observeNamed("canon: halted");
        assertThat(halted.haltedBeforeRanking()).isTrue();
        assertThat(halted.rankedRoles()).isEmpty();
    }

    @Test
    void ablatingEvolutionOccurred_dropsEvaluationFitness() {
        // Pending-evaluation proposes EVALUATE, whose gate ranks only the evaluation role —
        // so the corpus's "most load-bearing signal" effect shows as an evaluation-fitness drop
        // of W_SIGNAL*strength + recency here (merge is not ranked in this mode at all).
        FrozenState s = named("canon: pending-evaluation");
        Observation base = FrozenCycleObserver.observe(s.ctx(), s.world());
        Observation ablated = FrozenCycleObserver.observe(
                Perturbation.ablate(BasicSignals.EVOLUTION_OCCURRED).apply().apply(s.ctx()), s.world());
        assertThat(base.rankedRoles()).containsExactly("evaluation");
        assertThat(ablated.fitness().get("evaluation")).isLessThan(base.fitness().get("evaluation"));
    }

    @Test
    void plannerThrottle_blocksPlanner_untilStrongReplanOverride() {
        Observation throttled = observeNamed("canon: planner-throttled");
        assertThat(throttled.blockersByRole().get("planner"))
                .anyMatch(b -> b.contains("planning throttled"));

        Observation overridden = observeNamed("canon: planner-throttle-overridden");
        assertThat(overridden.blockersByRole().get("planner"))
                .noneMatch(b -> b.contains("planning throttled"));
    }

    @Test
    void buildBroken_boostsAnalysisAboveDepressedPlannerAndEvaluation() {
        Observation obs = observeNamed("canon: build-broken");
        assertThat(obs.topRankedRole()).isEqualTo("analysis");
        assertThat(obs.blockersByRole().get("planner")).contains("build_blocked");
    }

    /**
     * End-to-end field validation: for each harvested real cycle, the observer's predicted
     * first-executed role and mode must match what production actually selected/proposed in
     * that cycle. Known exception: log-11, where production proposed UNDIRECTED despite
     * REPETITION_DETECTED pinned at 3.0 — possible only via a proposer branch reading a
     * context field the snapshot does not record (likely the stagnation circuit breaker,
     * whose branch pre-empts the repetition REPLAN rule) — the pre-declared fidelity limit
     * of log-derived states.
     */
    @Test
    void logDerivedStates_observerPredictsProductionsFirstExecutedRoleAndMode() {
        for (FrozenState s : FrozenStateFixtures.logDerivedStates()) {
            if (s.name().startsWith("log-11")) continue;
            Observation obs = FrozenCycleObserver.observe(s.ctx(), s.world());
            assertThat(obs.mode()).as(s.name() + " mode").isEqualTo(s.recordedMode());
            // The observer predicts the coin-flip set: eligible roles within one jitter of the top
            // eligible role. A singleton when untied — production's pick must be a member.
            assertThat(coinFlipCandidates(obs)).as(s.name() + " first executed role")
                    .contains(s.recordedFirstSelected());
        }
    }

    /**
     * The freeze IS the instrument: every perturbation in the sweep applies to the same
     * state.ctx(), so observe() must be a pure function of it. CycleContextData is a record,
     * but its Map components could still be mutated in place by anything observe() calls —
     * this pins (a) the signals map is byte-for-byte untouched, (b) re-observing after an
     * interleaved perturbed observation reproduces the identical Observation.
     */
    @Test
    void observeIsAFreeze_inputStateUntouched_andObservationRepeatable() {
        for (FrozenState s : FrozenStateFixtures.all()) {
            // Value-level snapshot: fresh Signal instances with copied meta maps, so the
            // equality check below cannot be satisfied by comparing a mutated object to itself.
            Map<SignalType, Signal> before = valueSnapshot(s.ctx().signals());

            Observation first = FrozenCycleObserver.observe(s.ctx(), s.world());
            // interleave a perturbed observation — it must not disturb the frozen state either
            s.ctx().signals().keySet().stream().findFirst().ifPresent(type ->
                    FrozenCycleObserver.observe(
                            Perturbation.strength(type, 2.7).apply().apply(s.ctx()), s.world()));
            Observation second = FrozenCycleObserver.observe(s.ctx(), s.world());

            assertThat(s.ctx().signals()).as(s.name() + " signals untouched").isEqualTo(before);
            assertThat(second).as(s.name() + " repeat observation identical").isEqualTo(first);
        }
    }

    private static Map<SignalType, Signal> valueSnapshot(Map<SignalType, Signal> signals) {
        Map<SignalType, Signal> copy = new LinkedHashMap<>();
        signals.forEach((type, s) -> copy.put(type,
                new Signal(s.type(), s.strength(), s.decayPerCycle(), s.age(), s.source(),
                        s.meta() == null ? null : Map.copyOf(s.meta()))));
        return copy;
    }

    /** Eligible roles whose fitness is within production's jitter of the top eligible role. */
    private static List<String> coinFlipCandidates(Observation obs) {
        String first = obs.firstEligibleRole();
        if (first == null) return List.of();
        double top = obs.fitness().get(first);
        return obs.rankedRoles().stream()
                .filter(r -> obs.blockersByRole().getOrDefault(r, List.of("x")).isEmpty())
                .filter(r -> top - obs.fitness().get(r) < FrozenCycleObserver.JITTER)
                .toList();
    }

    @Test
    void logDerivedStates_loadAndProduceARanking() {
        List<FrozenState> states = FrozenStateFixtures.logDerivedStates();
        assertThat(states).isNotEmpty();
        for (FrozenState s : states) {
            Observation obs = FrozenCycleObserver.observe(s.ctx(), s.world());
            // mode may legitimately gate roles out (e.g. a REPLAN-shaped signal map ranks 3);
            // the state must still produce a non-empty ranking.
            assertThat(obs.rankedRoles()).as(s.name()).isNotEmpty();
        }
    }

    private static boolean recordedOrderCompatible(List<String> recorded, Observation base) {
        if (!recorded.containsAll(base.rankedRoles()) || recorded.size() != base.rankedRoles().size()) {
            return false; // different role set ranked => mode mismatch, not comparable
        }
        for (String a : base.fitness().keySet()) {
            for (String b : base.fitness().keySet()) {
                double gap = base.fitness().get(a) - base.fitness().get(b);
                if (gap > FrozenCycleObserver.JITTER
                        && recorded.indexOf(a) > recorded.indexOf(b)) {
                    return false;
                }
            }
        }
        return true;
    }

    // ---------------------------------------------------------------- pinned prompt reach (3c)

    /** Any strength change must reach the analysis prompt (NAME=strength render, 7a687f5) and
     *  the interpretation prompt (full signal map render). */
    @Test
    void strengthChange_reachesAnalysisAndInterpretationPrompts() {
        FrozenState s = named("canon: missing-symbol-fresh");
        Map<String, String> base = AgentPromptRenderer.renderAll(s.ctx());
        Map<String, String> perturbed = AgentPromptRenderer.renderAll(
                Perturbation.strength(BasicSignals.MISSING_SYMBOL, 2.0).apply().apply(s.ctx()));
        Map<String, AgentPromptRenderer.PromptDelta> deltas = AgentPromptRenderer.diff(base, perturbed);
        assertThat(deltas).containsKeys("analysis", "interpretation");
    }

    @Test
    void ablatedSignal_disappearsFromAnalysisPromptSignalsBlock() {
        FrozenState s = named("canon: missing-symbol-fresh");
        Map<String, String> base = AgentPromptRenderer.renderAll(s.ctx());
        Map<String, String> perturbed = AgentPromptRenderer.renderAll(
                Perturbation.ablate(BasicSignals.MISSING_SYMBOL).apply().apply(s.ctx()));
        AgentPromptRenderer.PromptDelta analysis = AgentPromptRenderer.diff(base, perturbed).get("analysis");
        assertThat(analysis).isNotNull();
        assertThat(analysis.touchedBlocks()).anyMatch(b -> b.contains("SIGNALS"));
    }

    /** DIVERGENCE_REQUEST's prompt reach is the divergent evolution path (via the agent's
     *  signal-driven decision the renderer mirrors). */
    @Test
    void divergenceRequest_switchesEvolutionPromptToDivergentPath() {
        FrozenState s = named("canon: missing-symbol-fresh"); // no STAGNATION/RECOMBINATION present
        CycleContextData diverging = s.ctx().withSignal(
                Signal.of(BasicSignals.DIVERGENCE_REQUEST, 1.0, 0.10, "sweep"));
        assertThat(AgentPromptRenderer.useDivergent(s.ctx())).isFalse();
        assertThat(AgentPromptRenderer.useDivergent(diverging)).isTrue();
        Map<String, AgentPromptRenderer.PromptDelta> deltas =
                AgentPromptRenderer.diff(AgentPromptRenderer.renderAll(s.ctx()), AgentPromptRenderer.renderAll(diverging));
        assertThat(deltas).containsKey("evolution");
    }

    private static FrozenState named(String name) {
        return FrozenStateFixtures.all().stream()
                .filter(s -> s.name().equals(name)).findFirst().orElseThrow();
    }

    private static Observation observeNamed(String name) {
        FrozenState s = named(name);
        return FrozenCycleObserver.observe(s.ctx(), s.world());
    }
}
